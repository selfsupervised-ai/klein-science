# provenance: original
"""Generate the stand-in's SymPy name table from the oracle's introspection table (GUEST-01).

    python3 conformance/oracles/sympy/gen_standin.py --names <names.json> [--check]

<names.json> is the table `introspect.py` writes in the SymPy oracle image, fetched by digest with
`cargo xtask store get <introspection_sha256 from conformance/oracles/images.json> target/oracle/names.json`.

The script writes two files:
- standin/sympy/__init__.py: one plain function per name in SymPy's runtime `__all__` (921 names: the 902-name
  literal plus 19 subpackages), in SymPy's order. Each raises NotImplementedError naming the unavailable name. The one
  exception is `__version__`, bound to the version string. Then `__all__` with those names in the same order.
- standin/sympy/abc.py: the same for the Symbol-valued public names of `sympy.abc`, in sorted order.

SymPy's own `sympy/abc.py` builds its namespace with `exec` and the `string` module. The stand-in must stay inside
the Monty subset (no exec, no classes, no decorators), so both files hold only plain `def`s and one `__all__` list.

The output is a deterministic function of the input bytes: fixed order, LF line endings, one trailing newline, and
the input's SHA-256 on line 2. With --check nothing is written; the exit status is 1 when either committed file
differs from what this script would write.

Runs on the host with the standard library only.
"""

import argparse
import hashlib
import json
import keyword
import os
import sys

SYMPY_VERSION = "1.14.0"
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
STANDIN_SYMPY = os.path.join(REPO, "standin", "sympy")

# Names of `__all__` bound to a plain value rather than a function: SymPy's own value, which needs no tool call.
# `__version__` is the only dunder in `__all__`; every other dunder is refused.
VALUES = {"__version__": SYMPY_VERSION}

INIT_DOC = '''"""The klein-science SymPy stand-in.

A guest program imports this package as `sympy`. It binds every name of SymPy 1.14.0's runtime `__all__`, in
SymPy's order: the 902 names of the `__all__` literal and the 19 subpackage names SymPy appends to it. `__version__`
is SymPy's version string; every other name is a plain function that raises NotImplementedError until a later phase
implements it. Importing the package, or any name from it, makes no tool call.

Every computation leaves the guest as one tool call through `sympy._tool.call`, encoded by the one Python JCS
encoder, `sympy._wire`.
"""
'''

ABC_DOC = '''"""The klein-science stand-in for `sympy.abc`.

It binds the Symbol-valued public names of SymPy 1.14.0's `sympy.abc`, in sorted order, each as a plain function
that raises NotImplementedError until a later phase builds Symbols. SymPy builds this namespace with `exec`; the
stand-in lists it statically, because guest code stays inside the Monty subset.
"""
'''


def fail(message):
    print("gen_standin: " + message, file=sys.stderr)
    sys.exit(2)


def check_name(name, where):
    """A name is interpolated into Python source, so it must be a plain identifier and nothing else."""
    if not isinstance(name, str) or not name.isidentifier() or keyword.iskeyword(name):
        fail(where + ": " + repr(name) + " is not a plain identifier")
    if name in VALUES and where == "all":
        return name
    if name.startswith("__") or not name.isascii():
        fail(where + ": " + repr(name) + " is a dunder or not ASCII")
    return name


def load(path):
    """Read and validate the introspection table; return (digest, top-level names, abc names)."""
    with open(path, "rb") as handle:
        data = handle.read()
    digest = hashlib.sha256(data).hexdigest()
    table = json.loads(data.decode("utf-8"))
    if table.get("sympy_version") != SYMPY_VERSION:
        fail("names.json is for sympy " + repr(table.get("sympy_version")) + ", expected " + SYMPY_VERSION)
    rows = table.get("all")
    abc = table.get("abc")
    if not isinstance(rows, list) or not isinstance(abc, list):
        fail("names.json has no 'all' and 'abc' lists")
    names = [check_name(row.get("name") if isinstance(row, dict) else None, "all") for row in rows]
    abc_names = [check_name(name, "abc") for name in abc]
    if len(set(names)) != len(names) or len(set(abc_names)) != len(abc_names):
        fail("names.json repeats a name")
    return digest, names, sorted(abc_names)


def render(provenance, digest, docstring, module, names):
    lines = [
        "# provenance: port sympy@sympy-" + SYMPY_VERSION + ":" + provenance + " (BSD-3-Clause)",
        "# Generated by conformance/oracles/sympy/gen_standin.py from introspection " + digest + ". Do not edit by hand.",
        docstring,
    ]
    for name in names:
        lines.append("")
        if module == "sympy" and name in VALUES:
            lines.append(name + " = " + json.dumps(VALUES[name]))
            lines.append("")
            continue
        lines.append("def " + name + "(*args, **kwargs):")
        lines.append(
            '    raise NotImplementedError("' + module + "." + name + ' is not available in the klein-science stand-in")'
        )
        lines.append("")
    lines.append("")
    lines.append("__all__ = [")
    for name in names:
        lines.append('    "' + name + '",')
    lines.append("]")
    return "\n".join(lines) + "\n"


def generate(names_path):
    digest, names, abc_names = load(names_path)
    return {
        os.path.join(STANDIN_SYMPY, "__init__.py"): render("sympy/__init__.py", digest, INIT_DOC, "sympy", names),
        os.path.join(STANDIN_SYMPY, "abc.py"): render("sympy/abc.py", digest, ABC_DOC, "sympy.abc", abc_names),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--names", required=True, help="the introspection table, names.json")
    parser.add_argument("--check", action="store_true", help="compare with the committed files; write nothing")
    args = parser.parse_args()

    outputs = generate(args.names)
    stale = []
    for path, text in outputs.items():
        data = text.encode("utf-8")
        if args.check:
            try:
                with open(path, "rb") as handle:
                    if handle.read() != data:
                        stale.append(path)
            except FileNotFoundError:
                stale.append(path)
        else:
            with open(path, "wb") as handle:
                handle.write(data)
            print("gen_standin: wrote " + os.path.relpath(path, REPO) + " (" + str(len(data)) + " bytes)")
    if stale:
        for path in stale:
            print("gen_standin: " + os.path.relpath(path, REPO) + " differs from the generator output", file=sys.stderr)
        sys.exit(1)
    if args.check:
        print("gen_standin: generated files match")


if __name__ == "__main__":
    main()
